    def canonical_name(name)
      normalized = normalize_name(name)
      MERGE_ALIASES.each do |canonical, aliases|
        return canonical if dedupe_key(canonical) == dedupe_key(normalized)
        return canonical if aliases.any? { |a| dedupe_key(a) == dedupe_key(normalized) }
      end
      normalized
    end

    def load_raw_names
      path = Rails.root.join("db/seeds/data/saqr_items.txt")
      raise "Missing \#{path}" unless path.exist?

      path.read.split("\\n").map(&:strip).reject(&:empty?)
    end

    def deduplicated_names
      seen = {}
      load_raw_names.each do |raw|
        canonical = canonical_name(raw)
        key = dedupe_key(canonical)
        next if seen.key?(key)

        seen[key] = canonical
      end
      seen.values.sort
    end

    def inventory_item?(name)
      return false if name.match?(/^اضاف/)

      name.match?(INVENTORY_PATTERN)
    end

    def menu_category(name)
      MENU_CATEGORY_RULES.each do |pattern, category|
        return category if name.match?(pattern)
      end

      inventory_item?(name) ? nil : "General"
    end

    def seed_menu_items!(company:)
      position = MenuItem.maximum(:position).to_i
      categories = {}

      deduplicated_names.each do |name|
        next if inventory_item?(name)

        cat_name = menu_category(name)
        categories[cat_name] ||= Category.find_or_create_by!(name: cat_name, company: company) do |c|
          c.position = Category.count
          c.active = true
        end

        position += 1
        MenuItem.find_or_create_by!(name: name, company: company) do |item|
          item.category = categories[cat_name]
          item.base_price_cents = 0
          item.tax_category = %w[Drinks Cafe].include?(cat_name) ? "beverage" : "food"
          item.available = true
          item.position = position
        end
      end
    end

    def seed_ingredients!(company:)
      dry_goods = IngredientCategory.find_or_create_by!(name: "Dry Goods") { |c| c.position = 3 }
      packaging = IngredientCategory.find_or_create_by!(name: "Packaging") { |c| c.position = 5 }
      sauces = IngredientCategory.find_or_create_by!(name: "Sauces & Condiments") { |c| c.position = 4 }
      produce = IngredientCategory.find_or_create_by!(name: "Produce") { |c| c.position = 1 }
      proteins = IngredientCategory.find_or_create_by!(name: "Proteins") { |c| c.position = 0 }
      dairy = IngredientCategory.find_or_create_by!(name: "Dairy") { |c| c.position = 2 }

      deduplicated_names.each do |name|
        next unless inventory_item?(name)

        category = if name.match?(/اكياس|كوب|شنط|غطاء|طبق|بكر|ورق|علبة|علبه|ظرف|باكينج/)
                     packaging
                   elsif name.match?(/اسبريد|صوص|كات|ماي|بود|سير|ilo|gsf|توابل|مرقة/)
                     sauces
                   elsif name.match?(/فراخ|لحم|بيف|استر|برو|بيض/)
                     proteins
                   elsif name.match?(/لبن|كري|حل|زبد/)
                     dairy
                   elsif name.match?(/بصل|طم|خس|جز|بطاط|فاك|فلف|نع|لمو|موز/)
                     produce
                   else
                     dry_goods
                   end

        Ingredient.find_or_create_by!(name: name, company: company) do |ing|
          ing.ingredient_category = category
          ing.unit = name.match?(/كيلو|ك\\)|لتر|جرد|جال| gallon|\\d+ك/) ? "kg" : "pieces"
          ing.reorder_threshold = 5
          ing.cost_per_unit_cents = 0
          ing.quantity_on_hand = 0
          ing.active = true
        end
      end
    end

