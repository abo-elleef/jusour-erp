# frozen_string_literal: true
# encoding: utf-8

items_path = File.expand_path("data/saqr_items.txt", __dir__)
items = File.read(items_path, encoding: "UTF-8").lines.map(&:strip).reject(&:empty?)

def normalize(name)
  name.to_s.strip.sub(/\.\z/, "").sub(/-\z/, "").squeeze(" ")
end

def build_merge_map(items)
  merge = {}

  items.group_by { |n| normalize(n) }.each do |_base, group|
    next if group.size < 2

    canonical = group.find { |g| !g.end_with?(".") && !g.end_with?("-") } || group.first
    aliases = group - [canonical]
    merge[canonical] = aliases if aliases.any?
  end

  [
    items.grep(/^عرض الع/),
    items.grep(/^عرض الش/),
    items.select { |n| n.match?(/^بام[بو]/) },
    items.select { |n| n.match?(/^براون/) },
    items.grep(/^كومبو \( فرايز/),
    items.select { |n| %w[موخيتوfoكلاسيك موخيتوكلاسيك].include?(n) },
    items.grep(/^ميني تارت روش/),
    items.grep(/تارت.*شوكليت كيك/)
  ].each do |group|
    next if group.size < 2

    canonical = group.find { |n| n.start_with?("ميني") && !n.end_with?(".") } ||
                group.find { |n| n.start_with?("ميني") }&.sub(/\.\z/, "") ||
                group.find { |n| !n.end_with?(".") && n.start_with?("ميني") } ||
                group.find { |n| n.start_with?("ميني") } ||
                group.find { |n| !n.end_with?(".") } ||
                group.min_by(&:length)
    canonical = normalize(canonical) if canonical&.end_with?(".")
    aliases = group - [canonical]
    next if aliases.empty?

    merge[canonical] = ((merge.delete(canonical) || []) + aliases).uniq
  end

  merge
end

MERGE = build_merge_map(items)

def canonicalize(name, merge)
  normalized = normalize(name)
  merge.each do |canon, aliases|
    return canon if normalize(canon) == normalized
    return canon if aliases.any? { |a| normalize(a) == normalized }
  end
  normalized
end

seen = {}
items.each do |raw|
  canonical = canonicalize(raw, MERGE)
  key = canonical.downcase
  seen[key] = canonical unless seen.key?(key)
end

merge_lines = MERGE.sort.map { |k, vals| "    #{k.inspect} => #{vals.inspect}," }.join("\n")

